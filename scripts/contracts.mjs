import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';
import openapiTS, { astToString } from 'openapi-typescript';

const root = fileURLToPath(new URL('../', import.meta.url));
const targets = ['openapi.json', 'comparison.schema.json', 'catalog.schema.json', 'api.d.ts']
  .map((name) => resolve(root, 'packages/contracts', name));
const before = targets.map((path) => existsSync(path) ? readFileSync(path, 'utf8') : null);
const localPython = resolve(root, '.venv', process.platform === 'win32' ? 'Scripts/python.exe' : 'bin/python');
const python = process.env.LAPDNA_PYTHON || (existsSync(localPython) ? localPython : 'python');
const exported = spawnSync(python, [resolve(root, 'scripts/export_contracts.py')], { cwd: root, stdio: 'inherit' });
if (exported.error || exported.status !== 0) {
  console.error(exported.error?.message || 'Python contract export failed. Install the API dependencies first.');
  process.exit(1);
}
const ast = await openapiTS(pathToFileURL(targets[0]));
writeFileSync(targets[3], '// Generated by npm run contracts. Do not edit.\n' + astToString(ast));
if (process.argv.includes('--check') && targets.some((path, index) => readFileSync(path, 'utf8') !== before[index])) {
  console.error('Generated contracts changed. Run npm run contracts and commit the resulting files.');
  process.exit(1);
}
console.log(process.argv.includes('--check') ? 'Contracts are current.' : 'Contracts generated.');
